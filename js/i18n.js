const Lang = {
  current: localStorage.getItem("geoland_lang") || "kk",

  t(key, vars) {
    let s = (I18N[this.current] && I18N[this.current][key]) || I18N.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(`{${k}}`, vars[k]);
      });
    }
    return s;
  },

  set(lang) {
    this.current = lang === "en" ? "en" : "kk";
    localStorage.setItem("geoland_lang", this.current);
    document.documentElement.lang = this.current === "kk" ? "kk" : "en";
    this.apply();
    window.dispatchEvent(new CustomEvent("langchange", { detail: this.current }));
  },

  apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const attr = el.getAttribute("data-i18n-attr");
      const val = this.t(key);
      if (attr) el.setAttribute(attr, val);
      else el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = this.t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll(".lang-toggle button").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === this.current);
    });
  },

  bindToggles() {
    document.querySelectorAll(".lang-toggle button").forEach((btn) => {
      btn.addEventListener("click", () => this.set(btn.dataset.lang));
    });
  },
};

window.Lang = Lang;
window.I18N = I18N;
