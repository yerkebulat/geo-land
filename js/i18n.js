const LANGS = ["kk", "en", "ru"];
const HTML_LANG = { kk: "kk", en: "en", ru: "ru" };
const LOCALES = { kk: "kk-KZ", en: "en-GB", ru: "ru-RU" };

const Lang = {
  current: (function () {
    const saved = localStorage.getItem("geoland_lang");
    return LANGS.indexOf(saved) >= 0 ? saved : "kk";
  })(),

  t(key, vars) {
    let s = (I18N[this.current] && I18N[this.current][key]) || I18N.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(`{${k}}`, vars[k]);
      });
    }
    return s;
  },

  /** Pick a per-language value: Lang.pick({ kk: "...", en: "...", ru: "..." }) */
  pick(map) {
    if (!map) return "";
    return map[this.current] != null ? map[this.current] : map.en != null ? map.en : map.kk;
  },

  /** Current display title for a stored test submission ("Practice test #1"), or "" */
  practiceTestTitle(sub) {
    const m = sub && sub.type === "test" && /^test-(\d+)$/.exec(sub.taskId || "");
    return m ? this.t("practice_test_n", { n: m[1] }) : "";
  },

  /** Locale for dates (toLocaleString) */
  locale() {
    return LOCALES[this.current] || "en-GB";
  },

  set(lang) {
    this.current = LANGS.indexOf(lang) >= 0 ? lang : "kk";
    localStorage.setItem("geoland_lang", this.current);
    document.documentElement.lang = HTML_LANG[this.current];
    this.apply();
    window.dispatchEvent(new CustomEvent("langchange", { detail: this.current }));
  },

  apply() {
    document.documentElement.lang = HTML_LANG[this.current] || "kk";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const attr = el.getAttribute("data-i18n-attr");
      const val = this.t(key);
      if (attr) el.setAttribute(attr, val);
      else el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = this.t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll(".lang-toggle button").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === this.current);
    });
  },

  bindToggles() {
    document.querySelectorAll(".lang-toggle button").forEach((btn) => {
      btn.addEventListener("click", () => this.set(btn.dataset.lang));
    });
  },
};

window.Lang = Lang;
window.I18N = I18N;
